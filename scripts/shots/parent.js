const { chromium, B, api, shot } = require('./lib.js')
;(async () => {
  await api('/devices/1', 'PATCH', { status: 'assigned', owner_ids: [2] })
  const br = await chromium.launch()
  const page = await (await br.newContext({ viewport: { width: 1280, height: 800 }, colorScheme: 'light' })).newPage()
  await page.goto(B + '/login'); await page.getByLabel('Username').fill('sam'); await page.getByLabel('Password').fill('rivera-demo-2026')
  await page.getByRole('button', { name: 'Log in' }).click(); await page.waitForURL(B + '/'); await page.waitForLoadState('networkidle'); await page.waitForTimeout(1500)
  await shot(page, 'today', { fullPage: true })
  await page.goto(B + '/devices'); await page.waitForLoadState('networkidle'); await page.waitForTimeout(1500)
  await shot(page, 'devices-raw', { fullPage: true })
  await br.close()
})().catch(e => { console.error(e); process.exit(1) })
