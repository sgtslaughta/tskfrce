export const EMOJI_GROUPS: { category: string; emoji: Emoji[] }[] = Object.entries(RAW).map(([category, rows]) => ({
  category,
  emoji: rows.map((row) => {
    const [head, keywords = ''] = row.split('|')
    const space = head.indexOf(' ')
    return { char: head.slice(0, space), name: head.slice(space + 1), keywords }
  }),
}))

/** Emoji whose name or keywords contain every word of `query`. */
export function searchEmoji(query: string): Emoji[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean)
  return EMOJI_GROUPS.flatMap((g) => g.emoji).filter((e) => {
    const hay = `${e.name} ${e.keywords}`
    return words.every((w) => hay.includes(w))
  })
}
